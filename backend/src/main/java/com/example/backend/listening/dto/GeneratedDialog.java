package com.example.backend.listening.dto;

public class GeneratedDialog {
  private String dialog;
  private GeneratedQuestion[] questions;

  public GeneratedDialog() {
  }

  public String getDialog() {
    return dialog;
  }

  public void setDialog(String dialog) {
    this.dialog = dialog;
  }

  public GeneratedQuestion[] getQuestions() {
    return questions;
  }

  public void setQuestions(GeneratedQuestion[] questions) {
    this.questions = questions;
  }
}
